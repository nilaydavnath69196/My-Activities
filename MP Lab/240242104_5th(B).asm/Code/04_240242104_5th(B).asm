
; EXP NO: 04
; EXP NAME: Password Checker
; ID_NAME: 240242104_NILAY DAV NATH

.MODEL SMALL
.STACK 100H

.DATA
MSG1 DB 'Enter Password: $'

OKMSG DB 10,13,'PASSWORD OK$'
ERR1 DB 10,13,'Need Uppercase Letter$'
ERR2 DB 10,13,'Need Lowercase Letter$'
ERR3 DB 10,13,'Need Digit$'
ERR4 DB 10,13,'Password Length Error$'

PASS DB 30 DUP('$')

LEN DB 0
UP DB 0
LOW DB 0
DIG DB 0

.CODE
MAIN PROC

MOV AX,@DATA
MOV DS,AX

LEA DX,MSG1
MOV AH,09H
INT 21H

LEA SI,PASS

INPUT:

MOV AH,01H
INT 21H

CMP AL,13
JE CHECK

MOV [SI],AL
INC SI

INC LEN

JMP INPUT

CHECK:

CMP LEN,6
JB LENGTHERR

CMP LEN,20
JA LENGTHERR

LEA SI,PASS

SCAN:

MOV AL,[SI]

CMP AL,'$'
JE RESULT

CMP AL,'A'
JB LOWERCHK

CMP AL,'Z'
JA LOWERCHK

MOV UP,1

LOWERCHK:

CMP AL,'a'
JB DIGCHK

CMP AL,'z'
JA DIGCHK

MOV LOW,1

DIGCHK:

CMP AL,'0'
JB NEXT

CMP AL,'9'
JA NEXT

MOV DIG,1

NEXT:
INC SI
JMP SCAN

RESULT:

CMP UP,1
JNE UERROR

CMP LOW,1
JNE LERROR

CMP DIG,1
JNE DERROR

LEA DX,OKMSG
MOV AH,09H
INT 21H
JMP ENDING

UERROR:
LEA DX,ERR1
MOV AH,09H
INT 21H
JMP ENDING

LERROR:
LEA DX,ERR2
MOV AH,09H
INT 21H
JMP ENDING

DERROR:
LEA DX,ERR3
MOV AH,09H
INT 21H
JMP ENDING

LENGTHERR:
LEA DX,ERR4
MOV AH,09H
INT 21H

ENDING:

MOV AH,4CH
INT 21H

MAIN ENDP
END MAIN