
; EXP NO: 02
; EXP NAME: Leap Year Checker
; ID_NAME: 240242104_NILAY DAV NATH

.MODEL SMALL
.STACK 100H

.DATA
MSG1 DB 'Enter The Year : $'

LEAP DB 10,13,'Leap Year$'
NOTL DB 10,13,'Not Leap Year$'

YEAR DW ?

.CODE
MAIN PROC

MOV AX,@DATA
MOV DS,AX

LEA DX,MSG1
MOV AH,09H
INT 21H

MOV AH,01H
INT 21H
SUB AL,30H

MOV AH,0
MOV BX,1000
MUL BX
MOV YEAR,AX

MOV AH,01H
INT 21H
SUB AL,30H

MOV AH,0
MOV BX,100
MUL BX
ADD YEAR,AX

MOV AH,01H
INT 21H
SUB AL,30H

MOV AH,0
MOV BX,10
MUL BX
ADD YEAR,AX

MOV AH,01H
INT 21H
SUB AL,30H

MOV AH,0
ADD YEAR,AX


MOV AX,YEAR
MOV DX,0
MOV BX,4
DIV BX

CMP DX,0
JE YES

LEA DX,NOTL
MOV AH,09H
INT 21H
JMP ENDING

YES:
LEA DX,LEAP
MOV AH,09H
INT 21H

ENDING:

MOV AH,4CH
INT 21H

MAIN ENDP
END MAIN