
.MODEL SMALL
.STACK 100H

.DATA

MSG1 DB 13,10,'SUCCESS$'
MSG2 DB 13,10,'FAILURE$'

.CODE
MAIN PROC

    MOV AX,@DATA
    MOV DS,AX

    MOV AH,01H
    INT 21H

    CMP AL,'7'
    JE OK

    LEA DX,MSG2
    MOV AH,09H
    INT 21H
    JMP EXIT

OK:
    LEA DX,MSG1
    MOV AH,09H
    INT 21H

EXIT:
    MOV AH,4CH
    INT 21H

MAIN ENDP
END MAIN
