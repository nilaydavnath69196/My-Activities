
; EXP NO: 01                  
; EXP NAME: String Manipulation  
; ID_Name: 240242104_Nilay Dav Nath


.MODEL SMALL
.STACK 100H
.DATA
MSG1 DB 'Enter String: $'
MSG2 DB 10,13,'Converted String: $'

STR DB 50 DUP('$')
.CODE
MAIN PROC
MOV AX,@DATA
MOV DS,AX
LEA DX,MSG1
MOV AH,09H
INT 21H
LEA SI,STR

INPUT:
MOV AH,01H
INT 21H

CMP AL,13
JE CONVERT

MOV [SI],AL
INC SI
JMP INPUT

CONVERT:

LEA SI,STR

NEXT:
MOV AL,[SI]

CMP AL,'$'
JE DISPLAY

CMP AL,'a'
JB CHECK2

CMP AL,'z'
JA CHECK2

SUB AL,32
MOV [SI],AL
JMP SKIP

CHECK2:

CMP AL,'A'
JB SKIP

CMP AL,'Z'
JA SKIP

ADD AL,32
MOV [SI],AL

SKIP:
INC SI
JMP NEXT

DISPLAY:

LEA DX,MSG2
MOV AH,09H
INT 21H

LEA DX,STR
MOV AH,09H
INT 21H

MOV AH,4CH
INT 21H

MAIN ENDP
END MAIN